import re
applied, skipped = 0, []
for key, when, where, age, what in FA:
    m = re.search(r"key: '" + key + r"',([\s\S]*?)\n  \},", s)
    if not m:
        skipped.append(key); continue
    seg = m.group(0)
    if "whatFa" in seg:
        continue
    new = seg
    new = re.sub(r"(when: '[^']*',)", r"\1\n    whenFa: '" + when + "',", new, count=1)
    new = re.sub(r"(where: '[^']*',)", r"\1\n    whereFa: '" + where + "',", new, count=1)
    new = re.sub(r"(age: '[^']*',)", r"\1\n    ageFa: '" + age + "',", new, count=1)
    new = re.sub(r"(what: '(?:[^'\\]|\\.)*',)", lambda mm: mm.group(1) + "\n    whatFa: '" + what + "',", new, count=1)
    s = s.replace(seg, new, 1)
    applied += 1

open(p, "w").write(s)
print("applied", applied, "of", len(FA))
for k in skipped: print("   skipped:", k)
